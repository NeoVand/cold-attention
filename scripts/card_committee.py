def main(models, repo):
    m = Path(models) / 'compare_first' / 'strongly_connected_components'
    cfgs = [json.loads((m / f'seed{k}' / 'config.json').read_text()) for k in range(3)]
    s = [c['scores']['test'] for c in cfgs]
    text = CARD.format(params=cfgs[0]['parameters'], s0=s[0], s1=s[1], s2=s[2], mean=st.mean(s), repo=repo)
    (Path(models) / 'README.md').write_text(text)
    print(Path(models) / 'README.md')


if __name__ == '__main__':
    main(*sys.argv[1:])
